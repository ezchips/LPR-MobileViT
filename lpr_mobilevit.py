import torch
import torch.nn as nn
from typing import List, Dict, Optional, Tuple

# ------------------------------ Single-template heads ------------------------------

class MultiPathHead(nn.Module):
    def __init__(self, in_dim: int, num_classes: List[int], hidden: int = 512, dropout: float = 0.1):
        super().__init__()
        self.N = len(num_classes)
        self.heads = nn.ModuleList([
            nn.Sequential(
                nn.Linear(in_dim, hidden),
                nn.GELU(),
                nn.Dropout(dropout),
                nn.Linear(hidden, C),
            )
            for C in num_classes
        ])

    def forward(self, g: torch.Tensor) -> List[torch.Tensor]:
        return [h(g) for h in self.heads]

class MultiPathOCR(nn.Module):
    def __init__(self, backbone: nn.Module, num_classes: List[int], hidden: int = 512, dropout: float = 0.1):
        super().__init__()
        self.backbone = backbone
        self.head = MultiPathHead(backbone.out_channels, num_classes, hidden=hidden, dropout=dropout)

    def forward(self, x) -> List[torch.Tensor]:
        g = self.backbone(x)
        logits = self.head(g)
        return logits

# ------------------------------ Multi-template router ------------------------------

class _FormatClassifier(nn.Module):
    def __init__(self, in_dim: int, n_templates: int, hidden: int = 256, dropout: float = 0.1):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(in_dim, hidden),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden, n_templates),
        )
    def forward(self, g: torch.Tensor) -> torch.Tensor:
        return self.net(g)

class _TemplateHeads(nn.Module):
    def __init__(self, in_dim: int, num_classes: List[int], hidden: int = 512, dropout: float = 0.1):
        super().__init__()
        self.paths = nn.ModuleList([
            nn.Sequential(
                nn.Linear(in_dim, hidden),
                nn.GELU(),
                nn.Dropout(dropout),
                nn.Linear(hidden, C),
            ) for C in num_classes
        ])
        self.positions = len(num_classes)
    def forward(self, g: torch.Tensor) -> List[torch.Tensor]:
        return [p(g) for p in self.paths]

class MultiTemplateOCR(nn.Module):
    def __init__(self, backbone: nn.Module, num_classes_per_template: List[List[int]],
                 fmt_hidden: int = 256, head_hidden: int = 512, head_dropout: float = 0.1):
        super().__init__()
        self.backbone = backbone
        self.T = len(num_classes_per_template)
        self.heads = nn.ModuleList([
            _TemplateHeads(backbone.out_channels, ncs, hidden=head_hidden, dropout=head_dropout)
            for ncs in num_classes_per_template
        ])
        self.positions_per_template = [len(ncs) for ncs in num_classes_per_template]
        self.Pmax = max(self.positions_per_template)
        self.format = _FormatClassifier(backbone.out_channels, self.T, hidden=fmt_hidden, dropout=head_dropout)

    def forward(self, x):
        g = self.backbone(x)
        fmt_logits = self.format(g)
        tpl_logits = [head(g) for head in self.heads]
        return fmt_logits, tpl_logits

    def loss_multi(self, outputs, targets_pad, template_idx, mask, lambda_fmt=0.2, ignore_index=-100, class_weights=None):
        fmt_logits, tpl_logits = outputs
        loss = nn.CrossEntropyLoss()(fmt_logits, template_idx) * float(lambda_fmt)
        for t, head_logits in enumerate(tpl_logits):
            sel = (template_idx == t)
            if not torch.any(sel):
                continue
            Nt = len(head_logits)
            for pos in range(Nt):
                logit = head_logits[pos][sel]
                y = targets_pad[sel, pos]
                if class_weights is not None and class_weights[t][pos] is not None:
                    ce = nn.CrossEntropyLoss(weight=class_weights[t][pos].to(logit.device), ignore_index=ignore_index)
                else:
                    ce = nn.CrossEntropyLoss(ignore_index=ignore_index)
                loss = loss + ce(logit, y)
        return loss

    @torch.no_grad()
    def decode(self, outputs, charsets_per_template, topk_templates: int=1):
        fmt_logits, tpl_logits = outputs
        fmt_prob = fmt_logits.softmax(dim=1)
        fmt_conf, tids = fmt_prob.max(dim=1)
        B = fmt_logits.size(0)
        texts, confs, tids_out = [], [], []
        for i in range(B):
            t = int(tids[i].item())
            tids_out.append(t)
            positions = len(tpl_logits[t])
            s = []; csum = 0.0
            for pos in range(positions):
                p = tpl_logits[t][pos][i].softmax(dim=0)
                conf, idx = p.max(dim=0)
                s.append(charsets_per_template[t][pos][int(idx.item())])
                csum += float(conf.item())
            texts.append(''.join(s))
            confs.append((csum / max(1,positions)) * float(fmt_conf[i].item()))
        return texts, confs, tids_out

