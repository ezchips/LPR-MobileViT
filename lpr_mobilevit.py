def strip_separators(s: str, separators: List[str]) -> str:
    out = s
    for sp in separators:
        out = out.replace(sp, "")
    return out

def pattern_to_regex(pattern: str, separators: List[str]) -> re.Pattern:
    # L -> [A-Z], # -> [0-9]; other chars are literals; allow optional separators in labels
    regex = []
    for ch in pattern:
        if ch == "L":
            regex.append("([A-Z])")
        elif ch == "#":
            regex.append("([0-9])")
        else:
            # literal separator
            regex.append(re.escape(ch))
    full = "^" + "".join(regex) + "$"
    return re.compile(full)

def encode_label_single(label: str, fmt: FormatConfig, uppercase: bool=True) -> List[int]:
    s = label.upper() if uppercase else label
    # remove separators to align with charsets positions
    s_compact = strip_separators(s, fmt.separators)
    if len(s_compact) != fmt.positions:
        raise ValueError(f"Label length {len(s_compact)} != positions {fmt.positions} for pattern {fmt.pattern}")
    indices = []
    pi = 0
    for token in fmt.pattern:
        if token in ("L","#"):
            ch = s_compact[pi]
            try:
                idx = fmt.charsets[pi].index(ch)
            except ValueError:
                raise ValueError(f"Character '{ch}' not in charset for position {pi}")
            indices.append(idx)
            pi += 1
    return indices

def try_match_template(label: str, mt: MultiFormatConfig) -> Optional[int]:
    s = label.upper()
    for i,t in enumerate(mt.templates):
        rx = pattern_to_regex(t.pattern, mt.separators)
        if rx.match(s):
            return i
    return None

def encode_label_multi(label: str, mt: MultiFormatConfig, template_idx: Optional[int], uppercase: bool=True) -> Tuple[int, List[int]]:
    s = label.upper() if uppercase else label
    if template_idx is None:
        template_idx = try_match_template(s, mt)
        if template_idx is None:
            raise ValueError(f"Could not match label '{label}' to any template")
    t = mt.templates[template_idx]
    # compact version
    compact = strip_separators(s, mt.separators)
    if len(compact) != t.positions:
        raise ValueError(f"Label '{label}' does not have expected number of tokens for template {t.id}")
    idxs = []
    for pos in range(t.positions):
        ch = compact[pos]
        charset = t.charsets[pos]
        ix = charset.find(ch)
        if ix < 0:
            raise ValueError(f"Character '{ch}' not allowed at position {pos} for template {t.id}")
        idxs.append(ix)
    return template_idx, idxs

