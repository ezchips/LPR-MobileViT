# Utilities for robust decoding at inference time:
# - confidence gating
# - char-level Top-K re-scoring (beam search over low-gap slots)
# These helpers operate on gathered logits for a *single* chosen template.

from typing import List, Tuple, Dict, Any
import numpy as np
import torch
import math

def _softmax_np(x: np.ndarray, axis: int = -1) -> np.ndarray:
    x = x - np.max(x, axis=axis, keepdims=True)
    e = np.exp(x)
    return e / np.sum(e, axis=axis, keepdims=True)

def per_slot_topk(gathered_logits: torch.Tensor, slot_charsets: List[str], pos_mask: List[bool], k: int = 2):
    """
    gathered_logits: [Pmax, Cmax] (torch) for one sample
    slot_charsets:   list[str]  characters allowed for each valid slot (length == num_valid_slots)
    pos_mask:        list[bool] length Pmax; True where a slot is valid, else padded
    Returns:
      topk_idx: List[np.ndarray]  (num_slots, k) indices in charset
      topk_prob: List[np.ndarray] (num_slots, k) softmax probs
    """
    assert gathered_logits.ndim == 2, "Expect [Pmax, Cmax]"
    g = gathered_logits.detach().cpu().numpy()
    topk_idx, topk_prob = [], []
    slot = 0
    for p, valid in enumerate(pos_mask):
        if not valid: 
            continue
        nC = len(slot_charsets[slot])
        v = g[p, :nC].astype(np.float32)
        prob = _softmax_np(v, axis=0)
        idx = np.argsort(-prob)[:k]
        topk_idx.append(idx)
        topk_prob.append(prob[idx])
        slot += 1
    return topk_idx, topk_prob

def stitch_from_indices(top_idx: List[int], slot_charsets: List[str], pattern: str) -> Tuple[str, str]:
    """
    Build (text, text_raw) given per-slot chosen indices and the template pattern.
    """
    chars = [slot_charsets[i][idx] for i, idx in enumerate(top_idx)]
    out, raw = [], []
    s = 0
    for ch in pattern:
        if ch in ('L', '#'):
            out.append(chars[s]); raw.append(chars[s]); s += 1
        else:
            out.append(ch)
    return ''.join(out), ''.join(raw)

def score_indices(sum_logits_np: List[np.ndarray], top_idx: List[int]) -> float:
    """
    Compute sum log prob given softmax probs lists per slot.
    """
    s = 0.0
    for i, idx in enumerate(top_idx):
        prob = float(sum_logits_np[i][idx])
        s += math.log(max(prob, 1e-9))
    return s

def charlevel_beam_rescore(gathered_logits_b: torch.Tensor,
                           slot_charsets: List[str],
                           pos_mask: List[bool],
                           pattern: str,
                           topk: int = 2,
                           max_flips: int = 2,
                           gap_delta: float = 0.20) -> Dict[str, Any]:
    """
    Return best candidate among:
     - top-1 string (baseline)
     - candidates formed by flipping up to `max_flips` slots to their 2nd-best option
       (only for slots where (p1 - p2) < gap_delta).
    Returns dict with keys: text, text_raw, avg_conf, used_beam(bool), flips(int)
    """
    # Top-k per slot
    tk_idx, tk_prob = per_slot_topk(gathered_logits_b, slot_charsets, pos_mask, k=topk)
    # baseline
    top1_idx = [int(idx[0]) for idx in tk_idx]
    base_text, base_raw = stitch_from_indices(top1_idx, slot_charsets, pattern)
    base_conf = float(np.mean([p[0] for p in tk_prob]))
    best = dict(text=base_text, text_raw=base_raw, avg_conf=base_conf, used_beam=False, flips=0, top_idx=top1_idx)

    # Identify ambiguous slots where gap < delta
    ambiguous = [i for i,(prob) in enumerate(tk_prob) if len(prob) >= 2 and (prob[0]-prob[1]) < gap_delta]
    ambiguous = ambiguous[:8]  # safety cap

    if not ambiguous or max_flips <= 0:
        return best

    # Precompute logprob arrays
    sum_logits_np = [p for p in tk_prob]

    # Try combinations of flipping up to max_flips slots
    from itertools import combinations
    def score_of(idx_list): return score_indices(sum_logits_np, idx_list)
    best_score = score_of(best['top_idx'])

    for r in range(1, min(max_flips, len(ambiguous)) + 1):
        for combo in combinations(ambiguous, r):
            cand = list(best['top_idx'])
            ok = True
            for i in combo:
                if len(tk_idx[i]) >= 2:
                    cand[i] = int(tk_idx[i][1])  # use 2nd best
                else:
                    ok = False; break
            if not ok: 
                continue
            s = score_of(cand)
            if s > best_score:
                text, raw = stitch_from_indices(cand, slot_charsets, pattern)
                conf = float(np.mean([sum_logits_np[i][cand[i]] for i in range(len(cand))]))
                best.update(text=text, text_raw=raw, avg_conf=conf, used_beam=True, flips=r, top_idx=cand)
                best_score = s

    return best

