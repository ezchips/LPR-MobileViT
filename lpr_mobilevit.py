import torch
from typing import List, Tuple

def accuracy_metrics(logits: List[torch.Tensor], targets: torch.Tensor) -> Tuple[float,float]:
    """
    For single-template evaluation.
    logits: list of [B, Ci]; targets: [B, N]
    """
    with torch.no_grad():
        preds = [l.argmax(dim=1) for l in logits]   # list of [B]
        preds = torch.stack(preds, dim=1)           # [B,N]
        correct = (preds == targets)
        char_acc = correct.float().mean().item()
        plate_acc = correct.all(dim=1).float().mean().item()
        return char_acc, plate_acc

