def collate_mt(batch, ignore_index: int=-100, Pmax: Optional[int]=None):
    """
    Batch of (img, y, t, path) with variable length y.
    Returns: images[B,3,H,W], y_pad[B,Pmax], t_idx[B], mask[B,Pmax], paths[list]
    """
    imgs, ys, tids, paths = [], [], [], []
    for (im, y, t, p) in batch:
        imgs.append(im); ys.append(y); tids.append(t); paths.append(p)
    imgs = torch.stack(imgs, dim=0)
    tids = torch.stack(tids, dim=0)
    if Pmax is None:
        Pmax = max([len(y) for y in ys])
    y_pad = torch.full((len(batch), Pmax), fill_value=ignore_index, dtype=torch.long)
    mask = torch.zeros((len(batch), Pmax), dtype=torch.bool)
    for i,y in enumerate(ys):
        L = len(y)
        y_pad[i, :L] = y
        mask[i, :L] = True
    return imgs, y_pad, tids, mask, paths

