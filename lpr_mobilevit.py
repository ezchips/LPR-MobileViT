def _resolve_csv_path(csv_path: str, p: str) -> str:
    """
    Resolve a row's 'path' robustly:
      - absolute paths are returned as-is
      - otherwise try:
        (a) relative to CSV dir
        (b) relative to the *parent* of CSV dir  (handles rows like 'tiny_dataset/...' when
            the CSV lives in '.../tiny_dataset/')
        (c) as-is from current working dir (last resort)
    """
    p = p.strip()
    if os.path.isabs(p):
        return os.path.normpath(p)

    csv_dir = os.path.dirname(os.path.abspath(csv_path))
    # (a) CSV dir
    cand1 = os.path.normpath(os.path.join(csv_dir, p))
    if os.path.exists(cand1):
        return cand1

    # (b) Parent of CSV dir — fixes the 'tiny_dataset/tiny_dataset' duplication case
    parent = os.path.dirname(csv_dir)
    cand2 = os.path.normpath(os.path.join(parent, p))
    if os.path.exists(cand2):
        return cand2

    # (c) Fallback: treat p relative to CWD
    return os.path.normpath(os.path.abspath(p))

