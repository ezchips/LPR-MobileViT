import torch
import torch.nn as nn
import torch.nn.functional as F

# ---- basic conv ----
class ConvBNAct(nn.Module):
    def __init__(self, in_ch, out_ch, k=3, s=1, p=None):
        super().__init__()
        if p is None: p = k//2
        self.conv = nn.Conv2d(in_ch, out_ch, k, s, p, bias=False)
        self.bn = nn.BatchNorm2d(out_ch)
        self.act = nn.SiLU(inplace=True)
    def forward(self, x):
        return self.act(self.bn(self.conv(x)))

# ---- MBConv (MobileNetV2 style inverted residual) ----
class MBConv(nn.Module):
    def __init__(self, in_ch, out_ch, s=1, expand=4):
        super().__init__()
        mid = in_ch * expand
        self.use_res = (s == 1 and in_ch == out_ch)
        self.block = nn.Sequential(
            # 1x1 expand
            nn.Conv2d(in_ch, mid, 1, 1, 0, bias=False),
            nn.BatchNorm2d(mid),
            nn.SiLU(inplace=True),
            # 3x3 depthwise
            nn.Conv2d(mid, mid, 3, s, 1, groups=mid, bias=False),
            nn.BatchNorm2d(mid),
            nn.SiLU(inplace=True),
            # 1x1 project
            nn.Conv2d(mid, out_ch, 1, 1, 0, bias=False),
            nn.BatchNorm2d(out_ch),
        )
    def forward(self, x):
        out = self.block(x)
        if self.use_res:
            out = out + x
        return out

# ---- Transformer layer (norm-first encoder) ----
def _make_transformer(d_model: int, nhead: int = 4, dim_feedforward: int = None, dropout: float = 0.0):
    if dim_feedforward is None:
        dim_feedforward = d_model * 2  # MobileViT uses 2d instead of 4d
    layer = nn.TransformerEncoderLayer(d_model=d_model, nhead=nhead, dim_feedforward=dim_feedforward,
                                       dropout=dropout, activation='gelu', batch_first=True, norm_first=True)
    return nn.TransformerEncoder(layer, num_layers=1)

class MobileViTBlock(nn.Module):
    def __init__(self, c_in: int, d_model: int, L: int = 2, patch: int = 2):
        super().__init__()
        self.patch = patch
        self.local = nn.Sequential(
            ConvBNAct(c_in, c_in, k=3, s=1),
            nn.Conv2d(c_in, d_model, 1, 1, 0, bias=False),
            nn.BatchNorm2d(d_model),
            nn.SiLU(inplace=True)
        )
        self.transformers = nn.ModuleList([_make_transformer(d_model) for _ in range(L)])
        self.proj = nn.Conv2d(d_model, c_in, 1, 1, 0, bias=False)
        self.fuse = ConvBNAct(c_in*2, c_in, k=3, s=1)

    def forward(self, x):
        B, C, H, W = x.shape
        p = self.patch
        assert (H % p == 0) and (W % p == 0), f"H and W must be multiples of patch={p}. Got {H}x{W}"

        y_local = self.local(x)                     # [B, d, H, W]
        d = y_local.shape[1]

        # Unfold into patches of size p x p with stride p
        unfold = F.unfold(y_local, kernel_size=p, stride=p)    # [B, d*p*p, N]
        N = unfold.shape[-1]
        # Reshape to [B*p*p, N, d]
        y = unfold.transpose(1,2).contiguous().view(B, N, d*p*p)
        # But we want P sequences (p*p), each with [B, N, d]
        y = unfold.view(B, d, p*p, N).permute(0,2,3,1).contiguous()  # [B, P, N, d]
        y = y.view(B*p*p, N, d)

        # Apply L transformer layers
        for enc in self.transformers:
            y = enc(y)  # [B*P, N, d]

        # Fold back
        y = y.view(B, p*p, N, d).permute(0,3,1,2).contiguous()  # [B, d, P, N]
        y = y.view(B, d*p*p, N)
        y = F.fold(y, output_size=(H, W), kernel_size=p, stride=p)   # [B, d, H, W]

        y = self.proj(y)                             # [B, C, H, W]
        out = self.fuse(torch.cat([x, y], dim=1))    # [B, C, H, W]
        return out

class MobileViTBackbone(nn.Module):
    """
    Returns global pooled feature vector g: [B, C_out]
    """
    def __init__(self, in_ch=3, channels=(64,80,96), dims=(96,120,144), depths=(2,4,3), patch=2, expand=4):
        super().__init__()
        c1, c2, c3 = channels
        d1, d2, d3 = dims
        L1, L2, L3 = depths
        self.patch = patch

        self.stem = ConvBNAct(in_ch, 16, k=3, s=2)
        self.mv2_1 = MBConv(16, 16, s=1, expand=expand)
        self.mv2_2 = MBConv(16, 24, s=2, expand=expand)  # 1/4
        self.mv2_3 = MBConv(24, c1, s=1, expand=expand)
        self.mvit_1 = MobileViTBlock(c_in=c1, d_model=d1, L=L1, patch=patch)

        self.mv2_4 = MBConv(c1, c2, s=2, expand=expand)  # 1/8
        self.mvit_2 = MobileViTBlock(c_in=c2, d_model=d2, L=L2, patch=patch)

        self.mv2_5 = MBConv(c2, c3, s=2, expand=expand)  # 1/16
        self.mvit_3 = MobileViTBlock(c_in=c3, d_model=d3, L=L3, patch=patch)

        self.out_channels = c3
        self.gap = nn.AdaptiveAvgPool2d((1,1))

    def forward(self, x):
        x = self.stem(x)
        x = self.mv2_1(x)
        x = self.mv2_2(x)
        x = self.mv2_3(x)
        x = self.mvit_1(x)
        x = self.mv2_4(x)
        x = self.mvit_2(x)
        x = self.mv2_5(x)
        x = self.mvit_3(x)
        g = self.gap(x).flatten(1)
        return g

