IMAGENET_MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
IMAGENET_STD  = np.array([0.229, 0.224, 0.225], dtype=np.float32)

def letterbox(img, new_shape=(128, 256), color=(114,114,114)):
    h, w = img.shape[:2]
    new_h, new_w = new_shape
    r = min(new_w / w, new_h / h)
    resized = cv2.resize(img, (int(w * r), int(h * r)), interpolation=cv2.INTER_LINEAR)
    pad_w, pad_h = new_w - resized.shape[1], new_h - resized.shape[0]
    top = pad_h // 2
    bottom = pad_h - top
    left = pad_w // 2
    right = pad_w - left
    out = cv2.copyMakeBorder(resized, top, bottom, left, right, cv2.BORDER_CONSTANT, value=color)
    return out

def _random_brightness_contrast(img, b=0.15, c=0.15):
    """
    Supports two APIs:

    1) Legacy scalar magnitudes (additive brightness, multiplicative contrast around 1):
         - b: float in [0, ..] → brightness shift magnitude as a fraction of 255
         - c: float in [0, ..] → contrast jitter magnitude (alpha = 1 ± c)

    2) YAML-style ranges (multiplicative factors):
         - b: (bmin, bmax) brightness multiplier range, e.g. (0.75, 1.25)
         - c: (cmin, cmax) contrast multiplier range around image mean, e.g. (0.75, 1.25)
    """

    # If ranges (tuple/list) are provided → multiplicative semantics
    if isinstance(b, (tuple, list)) or isinstance(c, (tuple, list)):
        img = img.astype(np.float32)

        # Brightness multiplier (simple gain)
        if isinstance(b, (tuple, list)) and len(b) == 2:
            bf = random.uniform(float(b[0]), float(b[1]))
            img = img * bf
        elif isinstance(b, (int, float)) and b > 0:
            # legacy additive brightness shift
            beta = 255.0 * random.uniform(-float(b), float(b))
            img = img + beta

        # Contrast multiplier around the mean
        if isinstance(c, (tuple, list)) and len(c) == 2:
            cf = random.uniform(float(c[0]), float(c[1]))
            m = img.mean(axis=(0, 1), keepdims=True)
            img = (img - m) * cf + m
        elif isinstance(c, (int, float)) and c > 0:
            # legacy multiplicative contrast jitter
            alpha = 1.0 + random.uniform(-float(c), float(c))
            img = img * alpha

        img = np.clip(img, 0, 255).astype(np.uint8)
        return img

    # Legacy scalar path (both b and c are floats)
    if (isinstance(b, (int, float)) and b > 0) or (isinstance(c, (int, float)) and c > 0):
        alpha = 1.0 + random.uniform(-float(c), float(c)) if c > 0 else 1.0
        beta  = 255.0 * random.uniform(-float(b), float(b)) if b > 0 else 0.0
        img = np.clip(alpha * img + beta, 0, 255).astype(np.uint8)
    return img

def _random_motion_blur(img, p=0.15, k=(3,5)):
    if random.random() > p:
        return img
    ksize = random.choice(list(range(k[0], k[1]+1, 2)))
    kernel = np.zeros((ksize, ksize), dtype=np.float32)
    xs = random.choice([0,1])
    if xs == 0:
        kernel[ksize//2, :] = 1.0 / ksize
    else:
        kernel[:, ksize//2] = 1.0 / ksize
    return cv2.filter2D(img, -1, kernel)

def _random_perspective(img, p=0.2, max_warp=0.03):
    if random.random() > p:
        return img
    h, w = img.shape[:2]
    dx = max(1, int(max_warp * w))
    dy = max(1, int(max_warp * h))
    src = np.float32([[0,0],[w-1,0],[w-1,h-1],[0,h-1]])
    dst = np.float32([
        [random.randint(0,dx), random.randint(0,dy)],
        [w-1-random.randint(0,dx), random.randint(0,dy)],
        [w-1-random.randint(0,dx), h-1-random.randint(0,dy)],
        [random.randint(0,dx), h-1-random.randint(0,dy)]
    ])
    M = cv2.getPerspectiveTransform(src, dst)
    return cv2.warpPerspective(img, M, (w, h), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT, borderValue=(114,114,114))

def _extract_mean_std(cfg: dict | None):
    mean, std = IMAGENET_MEAN, IMAGENET_STD
    if isinstance(cfg, dict):
        # Preferred location
        if isinstance(cfg.get("input"), dict):
            if isinstance(cfg["input"].get("mean"), (list,tuple)):
                mean = np.array(cfg["input"]["mean"], dtype=np.float32)
            if isinstance(cfg["input"].get("std"), (list,tuple)):
                std  = np.array(cfg["input"]["std"],  dtype=np.float32)
        # Fallback (top-level)
        if isinstance(cfg.get("input_mean"), (list,tuple)):
            mean = np.array(cfg["input_mean"], dtype=np.float32)
        if isinstance(cfg.get("input_std"), (list,tuple)):
            std  = np.array(cfg["input_std"], dtype=np.float32)
    return mean, std

class _Compose:
    def __init__(self, height: int, width: int, train: bool,
                 aug_cfg: Optional[dict] = None, mean=None, std=None):
        self.height = int(height)
        self.width  = int(width)
        self.train  = bool(train)
        self.aug    = aug_cfg or {}
        self.mean   = IMAGENET_MEAN if mean is None else np.array(mean, dtype=np.float32)
        self.std    = IMAGENET_STD  if std  is None else np.array(std, dtype=np.float32)

    def __call__(self, image) -> Dict[str, torch.Tensor]:
        img = image
        img = letterbox(img, (self.height, self.width))
        if self.train:
            p_persp = float(self.aug.get("perspective_prob", self.aug.get("persp_prob", 0.25)))
            max_warp = float(self.aug.get("max_warp", 0.04))
            p_mblur  = float(self.aug.get("motion_blur_prob", 0.20))
            b_rng    = tuple(self.aug.get("brightness", [0.88, 1.12]))
            c_rng    = tuple(self.aug.get("contrast",   [0.90, 1.10]))
            img = _random_perspective(img, p=p_persp, max_warp=max_warp)
            img = _random_motion_blur(img, p=p_mblur, k=(3,7))
            img = _random_brightness_contrast(img, b=b_rng, c=c_rng)

        img = img.astype(np.float32) / 255.0
        img = (img - self.mean) / self.std
        tensor = torch.from_numpy(img).permute(2,0,1).contiguous()
        return {"image": tensor}

def build_train_augs(height: int, width: int, cfg: dict | None = None):
    mean, std = _extract_mean_std(cfg)
    aug = cfg.get("augment", {}) if isinstance(cfg, dict) else None
    return _Compose(height, width, train=True, aug_cfg=aug, mean=mean, std=std)

def build_val_augs(height: int, width: int, cfg: dict | None = None):
    mean, std = _extract_mean_std(cfg)
    return _Compose(height, width, train=False, aug_cfg=None, mean=mean, std=std)

